import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const DOCS_DIR = path.resolve(SCRIPT_DIR, '..');
const SOURCE_DIR = path.join(DOCS_DIR, 'source');
const INPUT_CONFIG = path.join(DOCS_DIR, 'myst.yml');
const OUTPUT_CONFIG = path.join(DOCS_DIR, 'myst-serve.yml');

const FORMALISM_ROOT = 'source/1_hypostructure_formalism/intro_hypostructure.md';
const DATASET_ROOT = 'source/dataset/dataset.md';
const KEEP_TOP_LEVEL_FILES = new Set(['index.md', FORMALISM_ROOT, DATASET_ROOT]);
const KEEP_SOURCE_DIRS = new Set(['1_hypostructure_formalism', 'dataset']);
const KEEP_BIBLIOGRAPHY = [
  'source/1_hypostructure_formalism/references.bib',
  'source/references_compat.bib',
];
const STATIC_FILES = [
  '_static/custom.css',
  '_static/hypostructure-formalism-bundle.js',
  '_static/hypostructure-download-widget.css',
  '_static/hypostructure-download-widget.js',
  '_static/hypostructure-prompt-builder.html',
];

function indentOf(line) {
  return line.match(/^\s*/)[0].length;
}

function fileExists(relativePath) {
  return fs.existsSync(path.join(DOCS_DIR, relativePath));
}

function findProjectTocBounds(lines) {
  const tocStart = lines.findIndex((line) => line === '  toc:');

  if (tocStart === -1) {
    throw new Error('Could not find project.toc in docs/myst.yml');
  }

  const tocEnd = lines.findIndex((line, index) => {
    return index > tocStart && /^  [A-Za-z_][\w-]*:\s*$/.test(line);
  });

  if (tocEnd === -1) {
    throw new Error('Could not find the end of project.toc in docs/myst.yml');
  }

  return { tocStart, tocEnd };
}

function splitTopLevelTocBlocks(tocLines) {
  const blocks = [];
  let current = [];

  tocLines.forEach((line) => {
    if (/^    - file:\s+/.test(line)) {
      if (current.length > 0) blocks.push(current);
      current = [line];
      return;
    }

    if (current.length > 0) current.push(line);
  });

  if (current.length > 0) blocks.push(current);
  return blocks;
}

function tocRootFile(block) {
  const match = block[0].match(/^\s+- file:\s+(.+)$/);
  return match ? match[1].trim() : undefined;
}

function filterMissingTocEntries(block, includedFiles, skippedFiles) {
  const output = [];

  for (let index = 0; index < block.length;) {
    const line = block[index];
    const fileMatch = line.match(/^(\s*)- file:\s+(\S+\.md)\s*$/);

    if (fileMatch) {
      const itemIndent = indentOf(line);
      const file = fileMatch[2];

      if (!fileExists(file)) {
        skippedFiles.push(file);
        index += 1;
        while (index < block.length) {
          const nextLine = block[index];
          const trimmed = nextLine.trim();

          if (trimmed.startsWith('- ') && indentOf(nextLine) <= itemIndent) break;
          index += 1;
        }
        continue;
      }

      includedFiles.add(file);
    }

    output.push(line);
    index += 1;
  }

  return output;
}

function collectMarkdownFiles(rootDir) {
  const files = [];

  fs.readdirSync(rootDir, { withFileTypes: true }).forEach((entry) => {
    const absolutePath = path.join(rootDir, entry.name);

    if (entry.isDirectory()) {
      files.push(...collectMarkdownFiles(absolutePath));
      return;
    }

    if (entry.isFile() && entry.name.endsWith('.md')) {
      files.push(path.relative(DOCS_DIR, absolutePath).split(path.sep).join('/'));
    }
  });

  return files;
}

function buildExcludePatterns(includedFiles) {
  const excludes = [];

  fs.readdirSync(SOURCE_DIR, { withFileTypes: true }).forEach((entry) => {
    if (entry.isDirectory() && !KEEP_SOURCE_DIRS.has(entry.name)) {
      excludes.push(`source/${entry.name}/**`);
    }
  });

  KEEP_SOURCE_DIRS.forEach((dir) => {
    collectMarkdownFiles(path.join(SOURCE_DIR, dir)).forEach((file) => {
      if (!includedFiles.has(file)) excludes.push(file);
    });
  });

  return [...new Set(excludes)].sort();
}

function yamlList(items, indent = '    ') {
  return items.map((item) => `${indent}- ${item}`);
}

function main() {
  const configText = fs.readFileSync(INPUT_CONFIG, 'utf8');
  const lines = configText.split(/\r?\n/);
  const { tocStart, tocEnd } = findProjectTocBounds(lines);
  const projectPrefix = lines.slice(0, tocStart);
  const tocLines = lines.slice(tocStart + 1, tocEnd);
  const includedFiles = new Set();
  const skippedFiles = [];
  const prunedTocBlocks = splitTopLevelTocBlocks(tocLines)
    .filter((block) => KEEP_TOP_LEVEL_FILES.has(tocRootFile(block)))
    .map((block) => filterMissingTocEntries(block, includedFiles, skippedFiles))
    .filter((block) => block.length > 0);
  const excludePatterns = buildExcludePatterns(includedFiles);
  const bibliography = KEEP_BIBLIOGRAPHY.filter(fileExists);
  const outputLines = [
    '# Generated by docs/scripts/build_serve_config.mjs.',
    '# Serve-only config: keep the dev server scoped to formalism and dataset pages.',
    ...projectPrefix,
    '  toc:',
    ...prunedTocBlocks.flat(),
    '',
    '  # Serve-only excludes keep non-TOC files and non-dev source sections out of the watcher.',
    '  exclude:',
    ...yamlList(excludePatterns),
    '',
    '  # Bibliography needed by the formalism/dataset subset.',
    '  bibliography:',
    ...yamlList(bibliography),
    '',
    'site:',
    '  title: Hypostructure',
    '  template: book-theme',
    '  options:',
    '    favicon: ""',
    '    logo: ""',
    '    hide_toc: false',
    '    static_files:',
    ...yamlList(STATIC_FILES, '      '),
    '  nav:',
    '    - title: Home',
    '      url: /index',
    '    - title: Hypostructure Formalism',
    '      url: /intro-hypostructure',
    '    - title: Dataset',
    '      url: /dataset',
    '',
  ];

  fs.mkdirSync(path.dirname(OUTPUT_CONFIG), { recursive: true });
  fs.writeFileSync(OUTPUT_CONFIG, outputLines.join('\n'));

  console.log(
    `Wrote ${path.relative(DOCS_DIR, OUTPUT_CONFIG)} with ${includedFiles.size} pages, ` +
    `${excludePatterns.length} excludes, and ${bibliography.length} bibliography files.`,
  );
  skippedFiles.forEach((file) => {
    console.warn(`Skipped missing TOC file from serve config: ${file}`);
  });
}

main();
